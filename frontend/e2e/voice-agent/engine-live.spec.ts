import path from 'node:path';
import { VoiceCallChannel } from '@aixellabs/backend/db/types';
import { expect, test } from '../support/fixtures';
import { USER_STORAGE_STATE } from '../support/env';
import { E2E_USER } from '../support/users';
import { FAKE_MIC_LAUNCH_ARGS, openVoiceAgent } from '../support/voice-agents';

/**
 * The playground against the REAL voice engine and the real model, end to end. Skipped unless
 * `VOICE_E2E_ENGINE=1`, because it needs the engine running on the e2e port against the e2e Mongo:
 *
 *   cd backend/voice && MONGODB_URI=mongodb://127.0.0.1:27018 MONGODB_DB_NAME=AixelLabsE2E \
 *     .venv/bin/python phone.py --port 7862
 *   VOICE_E2E_ENGINE=1 E2E_VOICE_ENGINE_SECRET=<the engine's VOICELAB_KEY> E2E_GEMINI_API_KEY=<a real Gemini key> \
 *     VOICE_E2E_CALLER_WAV=<a wav of someone talking> pnpm --filter frontend exec playwright test e2e/voice-agent/engine-live.spec.ts
 */
test.skip(process.env.VOICE_E2E_ENGINE !== '1', 'needs the real voice engine on the e2e port');

const callerWav = process.env.VOICE_E2E_CALLER_WAV ?? '';

test.use({
    storageState: USER_STORAGE_STATE,
    permissions: ['microphone'],
    launchOptions: {
        args: [...FAKE_MIC_LAUNCH_ARGS, ...(callerWav ? [`--use-file-for-fake-audio-capture=${path.resolve(callerWav)}`] : [])],
    },
});

test.beforeEach(async ({ db }) => {
    await db.resetUser(E2E_USER);
    await db.resetVoiceAgents(E2E_USER);
    await db.resetVoiceTelephony(E2E_USER);
});

test('a playground call reaches the engine, she talks, the caller is heard, and the call is logged', async ({ page, db }) => {
    test.setTimeout(120_000);
    const agentId = await db.insertVoiceAgent(E2E_USER, {
        name: 'Live test',
        voice: 'kore',
        prompt: 'You are Maya, a receptionist for Sunrise Dental. Keep every reply to one short sentence.',
        callNotes: 'Open by saying thanks for calling Sunrise Dental.',
    });
    await openVoiceAgent(page, agentId);

    await page.getByRole('button', { name: 'Start call' }).click();
    await expect(page.getByTestId('playground-status')).toHaveText('Live', { timeout: 15_000 });
    // Her opener, generated by the model for this agent's prompt.
    await expect(page.getByText(/sunrise dental/i).first()).toBeVisible({ timeout: 20_000 });
    // The fake microphone's caller line, heard and transcribed by the engine, then a reply.
    await expect(page.getByText(/go ahead|minute/i).first()).toBeVisible({ timeout: 40_000 });
    await expect(page.getByText(/answered in [\d.]+ s/i).first()).toBeVisible({ timeout: 20_000 });

    await page.getByRole('button', { name: /end call/i }).click();
    await expect
        .poll(async () => (await db.getVoiceCalls(E2E_USER)).length, { timeout: 15_000 })
        .toBe(1);
    const [call] = await db.getVoiceCalls(E2E_USER);
    expect(call.channel).toBe(VoiceCallChannel.PLAYGROUND);
    expect(call.agentId.toString()).toBe(agentId);
    expect(call.voice).toBe('kore');
    expect(call.turns.some((t) => t.role === 'agent')).toBe(true);
    expect(call.turns.some((t) => t.role === 'caller')).toBe(true);
    // Priced from Gemini's own token counts; a playground call has no phone part.
    expect(call.cost?.geminiTokens.audioOut).toBeGreaterThan(0);
    expect(call.cost?.provider).toBeUndefined();
    expect(call.cost?.totalUsd).toBe(call.cost?.geminiUsd);

    // The call shows up in the call log the user sees.
    await page.goto('/voice-agent/call-logs');
    await expect(page.getByText('Live test').first()).toBeVisible();
});
